#!/usr/bin/env python3
"""Generate the OSD bitmap font ELF section (Scheme B).

The section is self-describing and deliberately little-endian so the same
container works on any ELF target, including big-endian ones.

Layout (offset 0 is the start of section `desmume_osd_fonts`):

    u8   magic[4]      "DSF1"
    u16  version       1
    u16  headerSize    16
    u32  totalSize     size of the whole section in bytes
    u16  count         number of font entries
    u16  reserved      0

    repeated `count` times:
    u16  nameLen
    u16  reserved      0
    u32  dataLen
    u8   name[nameLen] (no NUL)
    pad to 4 bytes
    u8   data[dataLen]
    pad to 4 bytes

The assembly defines `desmume_osd_fonts_anchor` at the start of the section.
The provider references that symbol so archive members and --gc-sections keep
the payload. The linker synthesizes __start_desmume_osd_fonts /
__stop_desmume_osd_fonts because the section name is a C identifier.

Usage:
    generate_elf_font_section.py OUTPUT.S [--font-dir DIR]
"""

from pathlib import Path
import argparse
import sys

# Canonical names/order from fonts_list[] in aggdraw.cpp. Do not reorder.
NAMES = [
    "gse4x6", "gse4x8", "gse5x7", "gse5x9", "gse6x9", "gse6x12",
    "gse7x11", "gse7x11_bold", "gse7x15", "gse7x15_bold",
    "gse8x16", "gse8x16_bold",
    "mcs11_prop", "mcs11_prop_condensed", "mcs12_prop", "mcs13_prop",
    "mcs5x10_mono", "mcs5x11_mono", "mcs6x10_mono", "mcs6x11_mono",
    "mcs7x12_mono_high", "mcs7x12_mono_low",
    "verdana12", "verdana12_bold", "verdana13", "verdana13_bold",
    "verdana14", "verdana14_bold", "verdana16", "verdana16_bold",
    "verdana17", "verdana17_bold", "verdana18", "verdana18_bold",
]

HEADER_SIZE = 16
ALIGN = 4


def align4(n):
    return (n + 3) & ~3


def le16(n):
    return ".byte 0x%02x, 0x%02x" % (n & 0xFF, (n >> 8) & 0xFF)


def le32(n):
    return ".byte 0x%02x, 0x%02x, 0x%02x, 0x%02x" % (
        n & 0xFF, (n >> 8) & 0xFF, (n >> 16) & 0xFF, (n >> 24) & 0xFF)


def asm_path(path):
    return path.as_posix().replace("\\", "\\\\").replace('"', '\\"')


def main():
    default_font_dir = Path(__file__).resolve().parent / "fonts"
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", help="assembly file to write")
    parser.add_argument("--font-dir", default=str(default_font_dir),
                        help="directory containing the 34 .bin payloads")
    args = parser.parse_args()

    font_dir = Path(args.font_dir).resolve()
    out_path = Path(args.output)

    blobs = []
    for name in NAMES:
        path = font_dir / (name + ".bin")
        data = path.read_bytes()
        if len(data) < 4:
            raise SystemExit("%s: too short" % path)
        blobs.append((name, data))

    offset = HEADER_SIZE
    entries = []
    for name, data in blobs:
        name_bytes = name.encode("ascii")
        data_off = align4(offset + 8 + len(name_bytes))
        end = align4(data_off + len(data))
        entries.append((name, name_bytes, data, data_off, end))
        offset = end

    total_size = offset
    if total_size > 0xFFFFFFFF:
        raise SystemExit("section too large")
    if len(entries) > 0xFFFF:
        raise SystemExit("too many fonts")

    for name, _name_bytes, _data, data_off, end in entries:
        if data_off % ALIGN != 0 or end % ALIGN != 0:
            raise AssertionError("bad alignment for " + name)

    lines = []
    lines.append("/* Generated by generate_elf_font_section.py; do not edit. */")
    lines.append('.section desmume_osd_fonts,"a",@progbits')
    lines.append(".balign 16")
    lines.append(".globl desmume_osd_fonts_anchor")
    lines.append(".type desmume_osd_fonts_anchor, @object")
    lines.append("desmume_osd_fonts_anchor:")
    lines.append("/* header */")
    lines.append('.ascii "DSF1"')
    lines.append(le16(1))                    # version
    lines.append(le16(HEADER_SIZE))          # header size
    lines.append(le32(total_size))           # total size
    lines.append(le16(len(entries)))         # count
    lines.append(le16(0))                    # reserved

    for name, name_bytes, data, data_off, end in entries:
        lines.append("/* %s: nameLen=%d dataLen=%d offset=%d */" % (
            name, len(name_bytes), len(data), data_off))
        lines.append(le16(len(name_bytes)))
        lines.append(le16(0))
        lines.append(le32(len(data)))
        lines.append('.ascii "%s"' % name)
        lines.append(".balign 4")
        lines.append('.incbin "%s"' % asm_path(font_dir / (name + ".bin")))
        lines.append(".balign 4")

    lines.append(".size desmume_osd_fonts_anchor, . - desmume_osd_fonts_anchor")
    lines.append('.section .note.GNU-stack,"",@progbits')
    lines.append("")

    out_path.write_text("\n".join(lines), encoding="ascii")
    print("wrote %s: %d fonts, %d bytes" % (out_path, len(entries), total_size))
    return 0


if __name__ == "__main__":
    sys.exit(main())
